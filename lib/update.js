function describeLane(id, listed, state, localVer, localRev) {
  const sha = id === "beta" ? listed.betaSha : listed.stableSha;
  const versions = listed.versions.filter((item) => item.channel === id);
  const latest = versions.find((item) => item.latest);
  const version = latest?.version || "";
  const onLane = state.channel === id;
  const matchesHead = Boolean(localRev && sha && sameRev(localRev, sha));
  const current = matchesHead;
  // Fork improvements can share the upstream package version. Revision identity
  // determines availability; installation separately enforces Git fast-forward.
  const hasUpdate = Boolean(onLane && sha && (!localRev || !sameRev(localRev, sha)));
  return {
    id,
    ref: CHANNELS[id].ref,
    version,
    sha: sha ? String(sha).slice(0, 7) : "",
    current,
    hasUpdate,
    hasRemote: Boolean(sha || versions.length),
  };
}

function lanesOf(listed, state, localVer, localRev) {
  return {
    stable: describeLane("stable", listed, state, localVer, localRev),
    beta: describeLane("beta", listed, state, localVer, localRev),
  };
}

export async function checkUpdate() {
  let state = readChannelState();
  const localVer = localVersion();
  const listed = await listRemoteVersions();
  const gitSha = gitOk() ? gitHead(PLUGIN_ROOT) : "";
  const stamp = readStamp();
  const localRev = gitSha || stamp;
  listed.versions = listed.versions.map((item) => ({ ...item, current: Boolean(localRev && sameRev(item.sha, localRev)) }));
  const channelRef = currentChannelRef(state);
  const lanes = lanesOf(listed, state, localVer, localRev);
  const lane = lanes[state.channel] || lanes.stable;
  if (!lane.hasRemote && state.channel === "beta") {
    return rememberUpdate({
      ok: true,
      hasUpdate: false,
      hasBeta: false,
      error: "还没有测试版",
      localVersion: localVer,
      remoteVersion: "",
      localSha: localRev ? localRev.slice(0, 7) : "",
      remoteSha: "",
      updateTarget: channelRef,
      via: detectVia(),
      versions: listed.versions,
      lanes,
      ...channelPublic(state),
    });
  }
  if (!lanes.stable.hasRemote) throw new Error(`无法读取个人 fork 分支 ${STABLE_REF}`);
  const result = {
    ok: true,
    hasUpdate: Boolean(lane.hasUpdate),
    hasBeta: listed.hasBeta,
    updateTarget: channelRef,
    pinned: Boolean(state.pin),
    localVersion: localVer,
    remoteVersion: lane.version || lane.sha,
    localSha: localRev ? localRev.slice(0, 7) : "",
    remoteSha: lane.sha,
    via: detectVia(),
    versions: listed.versions,
    lanes,
    ...channelPublic(state),
  };
  rememberUpdate(result);
  return result;
}

let lastUpdate = null;

function rememberUpdate(result) {
  lastUpdate = result && typeof result === "object" ? result : lastUpdate;
  return lastUpdate;
}

export function lastUpdateResult() {
  return lastUpdate;
}

function runGit(dir, args, timeout = 20000) {
  try {
    return execFileSync("git", ["-C", dir, ...args], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
      timeout,
    });
  } catch (e) {
    const detail = [e.stderr, e.stdout, e.message].filter(Boolean).join("\n").trim();
    throw new Error(detail || `git ${args.join(" ")}`);
  }
}

async function prepareArchive(sha, tmp) {
  const zip = path.join(tmp, "plugin.zip");
  const res = await fetchRes(archiveZipUrl(sha), 45000);
  await fsp.writeFile(zip, Buffer.from(await res.arrayBuffer()));
  extractZipArchive(zip, tmp);
  const candidates = [];
  for (const name of await fsp.readdir(tmp)) {
    const candidate = path.join(tmp, name);
    if (fs.existsSync(path.join(candidate, "package.json"))) candidates.push(candidate);
  }
  if (candidates.length !== 1) throw new Error("更新归档必须包含唯一的插件目录");
  await validateUpdatePackage(candidates[0]);
  return candidates[0];
}

let applyUpdateInflight = null;

export async function applyUpdate(jobs = planUpdates(), options = {}) {
  // 同一时刻只能有一次 applyUpdate 在跑。第二次调用在第一次完成前共享同一个 Promise,
  // 避免两条 overlayFromZip 同时往同一目录写出一半文件,或两次 writeStamp 竞争。
  if (applyUpdateInflight) return applyUpdateInflight;
  applyUpdateInflight = (async () => {
    try {
      return await _applyUpdateImpl(jobs, options);
    } finally {
      applyUpdateInflight = null;
    }
  })();
  return applyUpdateInflight;
}

async function _applyUpdateImpl(jobs, options) {
  if (!Array.isArray(jobs)) {
    options = jobs && typeof jobs === "object" ? jobs : {};
    jobs = planUpdates();
  }
  const requested = options.ref || STABLE_REF;
  // An old tag, upstream branch or arbitrary SHA is not an implicit rollback.
  if (requested !== STABLE_REF) throw new Error(`只允许更新个人 fork 分支 ${STABLE_REF}；旧标签和历史 pin 不会覆盖定制版`);
  const sha = await remoteHeadSha(STABLE_REF);
  if (!/^[a-f0-9]{40}$/i.test(sha)) throw new Error("无法固定更新到完整提交 SHA");
  const previous = readStamp();
  if (previous && previous !== sha) {
    const comparison = await fetchJson(`https://api.github.com/repos/${REPO}/compare/${previous}...${sha}`);
    if (comparison?.status !== "ahead") throw new Error("个人 fork 提交发生回退或分叉，已拒绝覆盖安装；只允许快进更新");
  }
  const tmp = await fsp.mkdtemp(path.join(os.tmpdir(), "dsh-purge-upd-"));
  try {
    const sourceDir = await prepareArchive(sha, tmp);
    const disabledHooks = await fsp.mkdtemp(path.join(tmp, '.empty-hooks-'));
    const seen = new Set();
    for (const job of jobs) {
      if (!job?.dir) throw new Error("更新目标缺少目录");
      const dir = realPath(job.dir);
      if (seen.has(dir)) continue;
      seen.add(dir);
      if (fs.existsSync(path.join(dir, ".git"))) {
        if (gitTrackedDirty(dir)) throw new Error(`本地插件文件有未提交修改，未覆盖: ${dir}`);
        // Never trust an installation's origin or silently overlay a failed Git
        // checkout. Fetch the same immutable commit downloaded above.
        runGit(dir, ["-c", `core.hooksPath=${disabledHooks}`, "fetch", "--no-tags", "--no-recurse-submodules",
          "--no-write-fetch-head", `https://github.com/${REPO}.git`, sha], 60000);
      }
    }
    const profiles = [...new Set(jobs.filter((job) => job.profileDir).map((job) => realPath(job.profileDir)))];
    for (const profile of profiles) {
      const pkg = readJson(path.join(profile, "package.json"));
      if (!pkg || !["dependencies", "devDependencies", "optionalDependencies"].some((key) => pkg[key]?.["dsh-purge"])) {
        throw new Error(`profile 缺少有效的 dsh-purge 安装记录: ${profile}`);
      }
    }
    const metadataFiles = [channelStatePath(), stampPath(), historyPath(), autoUpdateGuardPath(),
      ...profiles.map((profile) => path.join(profile, "package.json"))];
    const installed = await installPreparedUpdate({ sourceDir, sha, jobs,
      backupRoot: path.join(findDshHome(), "dsh-purge", "update-backups"), metadataFiles,
      writeMetadata: async ({ pkg }) => {
        for (const profile of profiles) pinInstalledSpec(profile, sha);
        writeChannelState({ channel: "stable", pin: "" });
        writeStamp(sha);
        markAutoUpdateGuard(STABLE_REF, sha);
        pushHistory({ ref: sha, sha, version: pkg.version, channel: "stable", source: UPDATE_SOURCE,
          label: versionLabel(pkg.version, "stable", sha), at: new Date().toISOString() });
      },
    });
    const version = installed.value.version;
    const state = { channel: "stable", pin: "" };
    const listed = { versions: [listedHead(sha, version, sha)], hasBeta: false, stableSha: sha, betaSha: "" };
    return rememberUpdate({ ok: true, filesUpdated: true, applied: false, needsApply: true,
      hasUpdate: false, hasBeta: false, pinned: false, localVersion: version, remoteVersion: version,
      localSha: sha.slice(0, 7), remoteSha: sha.slice(0, 7), needRestart: false,
      reloadClient: false, restartAfter: false, needsFullQuit: false, reapplied: false, needsRetry: false,
      backupPath: installed.backupPath,
      message: "插件文件已更新并保留备份；未应用宿主补丁或重启。请在方便时手动重载插件，再按需执行 Apply。",
      via: "protected-fork", versions: listed.versions, lanes: lanesOf(listed, state, version, sha), ...channelPublic(state) });
  } finally {
    await fsp.rm(tmp, { recursive: true, force: true }).catch(() => {});
  }
}

export async function switchChannel(channel, { apply = true } = {}) {
  if (channel !== "stable") throw new Error("个人 fork 仅提供受保护分支，不使用上游测试通道");
  return apply ? applyUpdate(planUpdates()) : checkUpdate();
}

export async function switchVersion(ref) {
  if (ref !== STABLE_REF) throw new Error("个人 fork 不通过旧标签回退；请使用已保留的更新备份恢复");
  return applyUpdate(planUpdates());
}

export async function handleUpdateOp(body = {}) {
  const op = String(body.op || (body.auto ? "auto" : "apply")).toLowerCase();
  if (["check", "status", "versions"].includes(op)) return checkUpdate();
  if (op === "channel") return switchChannel(body.channel, { apply: body.apply !== false });
  if (op === "switch" || op === "rollback") return switchVersion(body.ref || body.version || body.id);
  if (op === "auto") return autoUpdateIfNeeded();
  if (op !== "apply") throw new Error("未知更新操作");
  return applyUpdate(planUpdates(), { ref: body.ref || STABLE_REF });
}

export async function autoUpdateIfNeeded() {
  // 插件只允许用户在面板手动更新；启动路径永不自动升（版本适配依赖本机宿主）。
  return rememberUpdate({
    auto: true,
    skipped: "manual-only",
    hasUpdate: false,
    error: "",
    ...channelPublic(),
  });
}
